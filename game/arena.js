    // Раньше камню не хватало второй фазы. Он был только щитом: встать,
    // переждать удар, окаменеть снова. Защита без наказания, и против
    // каменного можно было просто стоять и копить откат. Теперь камень
    // ещё и единственный способ **выгнать толпу**: встал в середину,
    // собрал вокруг, крякнул — и все разлетелись.
    STONE_TIME: 1.3,
    STONE_COOLDOWN: 7,      // отсчёт от нажатия

    // Отскок бьющего при попадании в камень.
    //
    // Было 0.5, то есть отлетал на 150 — вдвое меньше, чем сам удар.
    // Стало 1.0: **защита стоит ровно столько же, сколько атака.**
    // Отбитый улетает на все 300.
    //
    // Это меняет камень из щита в оружие: если у каменного осталось
