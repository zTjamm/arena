/**
 * Серверный бот. Выдаёт тот же ввод { x, y, jump, push, stone }, что и
 * человек, и крутится в том же тике — никаких привилегий и никакого
 * доступа к состоянию кроме того, что видит игрок.
 *
 * Кнопки тут «удержательные», как у человека: `true` значит держать.
 * Для толчка это важно отдельно — он стреляет на отпускании, поэтому
 * бот обязан помнить, сколько тиков ещё копить заряд, иначе он
 * отпустит кнопку на следующем же тике и ударит в пустоту.
 *
 * Логика из трёх мыслей:
 *
 *   1. Толкать можно только с внутренней стороны. Чтобы вытолкнуть
 *      соперника наружу, нужно встать между ним и центром: иначе толчок
 *      пойдёт в обратную сторону и его ещё и придётся тащить обратно.
 *   2. Цель — тот, кто ближе всех к краю. Дальние штрафуются
 *      расстоянием, иначе бот бежит через всё поле за недосягаемым.
 *   3. Край важнее атаки. У самого края бот думает только о центре —
 *      иначе он вылетает первым, потратив всю атаку впустую.
 *
 * Дальше идут три вещи, без которых партия не кончается. Каждая из
 * них отдельно выглядит мелочью, но каждая ловилась тестом на тысячи
 * прогонов, поэтому описаны здесь подробно.
 *
 * ---
 *
 * **Волны атаки.** Двое, стоящие диаметрально, вынуждены занимать
 * внутреннюю сторону друг друга, а это для них обоих значит пересечь
 * центр навстречу. Раньше это давало зеркальный лобовой и вечный цикл.
 *
 * Разрывает его то, что волны у всех разные. Пока один бежит вперёд,
 * второй едет боком по касательной и не отвечает — встречаются они
 * косо, а косой удар отправляет кого-то в сторону, а не обратно по его
 * же траектории.
 *
 * ---
 *
 * **Жертву нельзя бросать.** Тест на многопользовательских партиях
 * дал 2607 смен цели за 6000 тиков: бот начинал толкать, видел рядом
 * кого-то выгоднее, бросал жертву и начинал заново. Жертва стояла на
 * месте, прогресс исчезал, и все восемь сидели в центре ещё 5970
 * тиков. Теперь цель держится несколько секунд и меняется только
 * явно на лучшую.
 *
 * ---
 *
 * **Отступать нельзя, когда уже давишь.** Толкающий держится на
 * расстоянии контакта ближе к центру, чем жертва — то есть границу
 * первой пересечёт жертва. Прежнее правило «край важнее атаки»
 * заставляло его отступать ровно в момент добивания, и жертва уезжала
 * к центру. Теперь в контакте бот продолжает давить, а поверх идёт
 * толчок по кнопке — он-то и есть главный способ довести соперника до
 * границы.
 *
 * Всё, что связано с краем, считается по запасу до ближайшей стороны
 * квадрата, а не по расстоянию до центра: угловой игрок дальше от
 * центра, но ближе к вылету, и по радиусу он выглядел бы спасшимся.
 *
 * Все числа — характеры — берутся из id игрока. Без них два одинаковых
 * бота зеркалят друг друга вечно: это то же различие, что есть между
 * живыми соперниками.
 */

'use strict';

const { T, marginOf } = require('./arena');

function clamp(v, lo, hi) {
    return v < lo ? lo : (v > hi ? hi : v);
}

function personality(id, cycle = 0) {
    let h = 2166136261;
    for (let i = 0; i < id.length; i++) {
        h ^= id.charCodeAt(i);
        h = Math.imul(h, 16777619);
    }
    h >>>= 0;

    // Длина волны пересчитывается на каждом цикле. Это не украшение:
    // характер берётся из id, а id могут совпасть. Партия a368/b368
    // встала намертво на 5000 тиков — у обоих вышло period=74 и
    // phase=95, волны шли байт в байт, геометрия зеркальная, и боты
    // кружили бок о бок, не меняясь, до самого конца. Классическое
    // совпадение хешей на маленьком диапазоне: 41 период на 103 фазы
    // дают 4223 комбинации, а на тысяче партий одно совпадение
    // ожидаемо. С номером цикла в зачёте совпасть можно ровно один
    // раз — дальше длины фаз уже разные и симметрия ломается.
    let hw = Math.imul(h ^ Math.imul(cycle >>> 0, 0x9e3779b9), 16777619);
    hw ^= hw >>> 15;
    hw = Math.imul(hw, 2246822507);
    hw ^= hw >>> 13;
    hw >>>= 0;

    return {
        // Запас до края, ниже которого думать уже только о центре.
        // Меньше число — наглее: идёт ближе к границе, прежде чем отступить.
        danger: T.PLAYER_RADIUS * 2 + 4 + (h % 18),
        // Насколько точно встать на линию рывка, чтобы рвануть.
        align: 0.86 + ((h >>> 5) % 10) / 100,
        // Порог для толчка. Он ниже порога рывка не случайно и не
        // «проще»: толчок бьёт туда, куда смотрит бот, а бот смотрит
        // сквозь цель наружу — выравнивать нужно именно ход, не выстрел.
        // Порог в 0.9 означал бы, что бот стреляет только в редкой
        // позиции бок о бок с жертвой, и партия виснет с полным откатом.
        pushAlign: 0.40 + ((h >>> 23) % 25) / 100,
        // На каком удалении прыгаем. От этого зависит, в какой тик
        // бот потратит откат — а значит, когда прыжок снова будет
        // готов. У всех порог разный, поэтому откаты не синхронизируются.
        jumpGap: 70 + ((h >>> 17) % 50),

        // Сколько ступеней держит толчок: 1, 2 или 3. Разброс нужен,
        // иначе все боты били бы одинаково и выигрывал бы тот, кто
        // дальше всех прыгает. Три ступени — самые сильные удары,
        // но их и ждать дольше, а это время бот стоит на месте.
        pushHold: 1 + ((h >>> 11) % 3),
        // С какого расстояния бот держит кнопку толчка. Кнопка не
        // требует касания, поэтому держать можно издалека — иначе
        // заряд негде набирать: соперник всё время отступает, и к
        // моменту касания копить уже поздно.
        pushApproach: 120 + (h % 140),
        // Длина волны атаки в тиках: 45–85, то есть 1.5–2.8 секунды.
        wavePeriod: 45 + (hw % 41),
        // Сдвиг фазы — начальная расстановка: кто-то стартует с атаки,
        // кто-то с отдыха.
        wavePhase: (h >>> 19) % 103,
        // Куда крутить между волнами: по часовой или против.
        circle: (h >>> 7) & 1 ? 1 : -1,
        // Сколько тиков держать выбранную жертву.
        commit: 45 + ((h >>> 13) % 40),
    };
}

function neutral() {
    return { x: 0, y: 0, jump: false, push: false, stone: false };
}

/**
 * Толчок теперь заряжается удержанием, и это меняет всё поведение бота.
 *
 * Раньше кнопка была на один тик: нажал — и улетело. Теперь кнопку надо
 * **держать** секунду-две-три, и только отпускание стреляет. Значит боту
 * нужно помнить, что он заряжает, сколько тиков ещё держать и кого
 * бить — состояние живёт в `ai.charge`, иначе бот отпускал бы кнопку
 * на следующем же тике и бил бы в пустоту.
 *
 * Порог решения — тот же, что был: бот бьёт, только стоя на внутренней
 * стороне жертвы. Но удерживать кнопку он продолжает и после того, как
 * цель на месте: заряд копится, пока бот в контакте.
 */
/** Ступень заряда по накопленному времени — та же формула, что в ядре. */
function tierOf(charge) {
    return Math.min(T.PUSH_TIERS.length, Math.floor(charge / T.PUSH_CHARGE_STEP + 1e-6));
}

/**
 * Насколько быстро игрок теряет запас до ближайшей границы.
 *
 * На квадрате запас — это половина стороны минус больший из модулей
 * координат, поэтому скорость потери — та из осей, которая убегает
 * наружу быстрее. По расстоянию до центра это не посчитать: угловой
 * игрок летит в угол и по радиусу почти не меняется.
 */
function marginLoss(p) {
    const rateX = p.x < 0 ? -p.vx : p.vx;
    const rateY = p.y < 0 ? -p.vy : p.vy;
    return Math.max(0, rateX, rateY);
}

/**
 * Ввод бота на один тик.
 */
function botInput(bot, arena) {
    // Летящий, прыгающий и каменный не управляют собой, и пытаться
    // что-то нажимать бессмысленно — ядро ввод всё равно игнорирует.
    if (bot.fly > 0 || bot.jumpLeft > 0 || bot.stone > 0) return neutral();

    const others = arena.players.filter(p => p.alive && p.id !== bot.id);
    if (!others.length) return neutral();

    const SIZE = arena.size;
    const p = personality(bot.id);

    const myMargin = marginOf(bot.x, bot.y, SIZE);
    const myD = Math.hypot(bot.x, bot.y);
    const centerDirX = myD > 1e-6 ? -bot.x / myD : 0;
    const centerDirY = myD > 1e-6 ? -bot.y / myD : 0;

    // Выбранная жертва. Состояние живёт на самом игроке и чисто
    // вычисляется заново при каждом новом матче, так что детерминизм
    // партии сохраняется.
    if (!bot.ai) bot.ai = { id: null, until: -1 };
    const ai = bot.ai;

    // Волна атаки. Личный счётчик фаз, а не глобальная формула по тику:
    // так длина каждой следующей фазы зависит и от id, и от того, сколько
    // волн уже прошло, и совпадение на первом цикле не тянется вечно.
    if (ai.phase === undefined) {
        const off = p.wavePhase % p.wavePeriod;
        ai.phase = off < p.wavePeriod * 0.6 ? 'attack' : 'rest';
        ai.phaseEnd = off + 1;
        ai.cycle = 0;
    }
    while (arena.tick >= ai.phaseEnd) {
        ai.phase = ai.phase === 'attack' ? 'rest' : 'attack';
        ai.cycle++;
        const pw = personality(bot.id, ai.cycle).wavePeriod;
        const attack = Math.max(6, Math.round(pw * 0.6));
        const rest = Math.max(6, pw - attack);
        ai.phaseEnd += ai.phase === 'attack' ? attack : rest;
    }
    const inWave = ai.phase === 'attack';

    // Ближе к краю — лучше. Запас отрицательным не бывает, а вот
    // расстояние до центра у центрального игрока мало — поэтому знак
    // минус: чем меньше запас, тем выше очки.
    const scoreOf = (o) => {
        const g = Math.hypot(o.x - bot.x, o.y - bot.y);
        return -marginOf(o.x, o.y, SIZE) - g * 0.3;
    };

    const held = ai.id ? others.find(o => o.id === ai.id) : null;
    let target = held;
    if (!held || arena.tick >= ai.until) {
        let best = null;
        let bestScore = -Infinity;
        for (const o of others) {
            const s = scoreOf(o);
            if (s > bestScore) {
                bestScore = s;
                best = o;
            }
        }
        // Держим прежнюю цель, пока новая не окажется заметно лучше:
        // иначе бот начинает толкать и тут же бросает жертву.
        if (held && bestScore < scoreOf(held) + 25) target = held;
        else target = best;
        ai.id = target.id;
        ai.until = arena.tick + p.commit;
    }

    const td = Math.hypot(target.x, target.y);
    const outX = td > 1e-6 ? target.x / td : 0;   // наружу от центра
    const outY = td > 1e-6 ? target.y / td : 0;

    const dx = target.x - bot.x;
    const dy = target.y - bot.y;
    const gap = Math.hypot(dx, dy);
    const align = gap > 1e-6 ? (dx * outX + dy * outY) / gap : 0;

    const contact = bot.radius * 2 + 6;
    const targetMargin = marginOf(target.x, target.y, SIZE);

    // Уже в контакте и при этом ближе к центру, чем жертва. По
    // построению моя маржа тогда больше её ровно на ширину контакта,
    // то есть границу первой пересечёт она, а не я.
    const inContact = gap <= contact + 12;

    // Кто атакует. Запас — это расстояние до края, и **чем он больше,
    // тем ближе к центру**. Мне надо стоять в центре, а жертву — между
    // мной и краем: только тогда удар уходит наружу и выносит.
    // Значит атакую, когда мой запас **больше** её: я внутри, она снаружи.
    //
    // Обратное условие было катастрофой и стоило 2000 партий: бот в
    // центре (запас 384) с жертвой у края (запас 55) объявлял себя
    // «наружным» и уходил, а жертва с запасом 55 объявлялась
    // «внутренней» и тоже уходила. Тридцать ударов за партию, и ни один
    // игрок не выбывал — партия не кончалась никогда.
    //
    // При равных запасах решает порядок ников: один раз и навсегда,
    // симметрия ломается и ловушка не возникает.
    //
    // Условие «align > 0» **не проверяется**. Бот смотрит на жертву
    // отдельным face, и удар уходит точно в неё с любой стороны —
    // проверять выравнивание было нечего. А проверка была, и она всё
    // ломала: двое, стоящие боком друг к другу, не проходили её никогда
    // и стояли в контакте до конца партии, ни разу не ударив.
    const tie = myMargin > targetMargin;
    const myTurn = myMargin >= targetMargin && bot.id < target.id;
    const winning = inContact && (tie || myTurn);

    // Толчок бьёт в направлении взгляда, а взгляд — отдельная от хода
    // штука. Смотрю я при этом прямо на цель: так проверка конуса в
    // ядре проходит всегда, а направленность удара — наружу или
    // касательно — задаётся не взглядом, а тем, стою ли я между
    // центром и жертвой (см. pushAlign). Без отдельного взгляда
    // отступление к центру разворачивало толчок в поле, и откат тикал
    // впустую.
    const faceN = gap || 1;
    const pushFace = { x: dx / faceN, y: dy / faceN };

    /**
     * Сборка ввода. Кнопки — level-based, то есть `true` значит
     * «держи», а не «нажми один раз»: пока откат кончился, скилл
     * сработает снова.
     *
     * Толчок из-за заряда — исключение и самая скользкая часть бота:
     * удар уходит **на отпускании**, поэтому держать и отпускать
     * кнопку надо по разным тикам, а взгляд — всё то же время
     * смотреть на цель. Потому `charge` (копим) и `release` (отпускаем)
     * разнесены: держать кнопку приходится не только когда удар
     * не нужен, но и когда он уже заряжен и вот-вот будет.
     *
     * Без этого разделения получается тупик: кнопка передаётся только
     * вместе с ударом, а заряд копится только пока кнопка нажата —
     * и бот не нажимает её никогда.
     */
    const move = (x, y, jump, stone, charge, release) => ({
        x, y, jump, stone,
        push: !!charge,
        face: charge || release ? pushFace : undefined,
    });

    /**
     * Обёртка: решение о движении может быть любым, а заряд — общий.
     *
     * Пока бот не готов к удару, кнопка держится **в каждой** ветке,
     * а не только в ветке атаки. Иначе получается ровно то, что и было
     * сломлено: бот подходит к сопернику из ветки «выживание», там
     * кнопка не передавалась, заряд не копился, и удар не уходил никогда
     * — на 20 000 тиков четыре игрока выбивали друг друга девять раз.
     *
     * Но и наоборот: когда бот готов ударить и стоит в контакте, все
     * прочие скиллы на этом тике молчат — иначе камень отменил бы
     * удар, а удар отменил бы защиту, и бот бездумно тратил бы откат.
     */
    const decide = (x, y, jump, stone) => {
        if (release) return move(x, y, jump, false, false, true);
        if (charge) return move(x, y, jump, false, true, false);
        return move(x, y, jump, stone, false, false);
    };

    // Камень включается, когда рядом кто-то есть: держать его
    // постоянно бот не может — откат 7 с, а стоит он 2.
    const wantStone = bot.cooldowns.stone <= 0 && gap < 90 && inContact;

    // Кнопку толчка держим, пока стоим в контакте на внутренней
    // стороне жертвы: именно там удар уходит наружу, а не в поле.
    // Добрав свою ступень — отпускаем, и удар уходит на отпускании.
    //
    // Порог ниже порога прыжка: толчок не двигает меня, а смотрит он
    // сквозь цель наружу, поэтому точность нужна постольку, поскольку
    // от неё зависит, куда улетит соперник.
    //
    // Копить можно и в контакте, и вблизи от него: заряд идёт
    // секунду-три, всё это время бот продолжает давить, а жертва —
    // отступать. Копить имеет смысл, пока бот не оторвался.
    //
    // canCharge — можно копить. charge — копим в этом тике. release —
    // в этом тике кнопку отпускаем, и удар уходит. Одно другому не
    // мешает: держать кнопку надо и когда заряд ещё копится, и когда
    // он уже набран и ждёт отпускания.
    //
    // Заряд НЕ обнуляется от того, что бот на секунду отошёл:
    // накопленное сохраняется, иначе заряд пришлось бы каждый раз
    // копить заново и толчок почти никогда не выстреливал бы.
    //
    // Заряд копится **на подходе**. Кнопка и ход независимы, и человек
    // именно так и играет: идёшь к сопернику, держишь пробел, удар
    // уходит, когда он уже под носом.
    //
    // Требовать контакт было неверно: соперник всё время отходит,
    // копится заряд только в момент касания, и на 4000 тиков вылетал
    // максимум один — партия не кончалась никогда.
    //
    // Главное правило: **кнопку нельзя отпускать, пока заряд не
    // добран**. Ядро стреляет на отпускании и обнуляет заряд, так что
    // отпустил раньше — выстрелил в пустоту и потерял накопленное.
    // Прежний вариант отпускал кнопку вместе с потерей позиции: на
    // 20 000 тиков вышло 334 отпускания и 5 ударов, то есть двадцать
    // ударов на пыль.
    //
    // Поэтому: держим, пока заряд не набран. Бить — только в контакте,
    // где удар действительно достанет.
    // Сколько ступеней набрать — **столько, чтобы хватило**. Запас жертвы
    // известен точно, значит известна и нужная ступень: отлёт должен
    // перекрыть запас с запасом, иначе жертва просто отскочит от края и
    // вернётся. Например, при запасе 60 отлёт в 100 приземляет её
    // ровно на границу — и она продолжает играть.
    //
    // Именно из-за этого партии не кончались: бот бил первой ступенью
    // (100 единиц) по всем подряд и никого не выносил.
    //
    // Если запас больше любой ступени, берём максимальную — больше
    // некуда, и там уже работает позиция.
    const need = Math.min(
        T.PUSH_TIERS.length,
        Math.ceil((targetMargin + 50) / T.PUSH_TIERS[0])
    );
    const want = Math.max(p.pushHold, need);
    const charged = tierOf(bot.charge) >= want;

    const canHold = bot.cooldowns.push <= 0 && gap < p.pushApproach;
    const charge = canHold && !charged;
    const release = charged && bot.cooldowns.push <= 0 && inContact;

    // Тормозной путь. Фиксированного порога мало: в рывке скорость 430,
    // торможение до нуля занимает около 47 единиц, а прежний порог был
    // 36–53. Бот успевал развернуться — и всё равно уходил за границу,
    // потому что места под торможение не осталось. Такое выбытие
    // выглядело как побег без толчка: никто его не толкал, он просто
    // не остановился. Развернуться нужно раньше, чем перестанет
    // хватать места, и это отменяет любую позицию, включая выигрышную.
    const stopDist = marginLoss(bot) ** 2 / (2 * T.ACCEL);
    const mustBrake = myMargin < stopDist + T.PLAYER_RADIUS;

    // Прыжок наружу. Он неуязвим, поэтому за край не выносит и
    // тормозного пути не требует: остановиться можно сразу.
    const canJump = (dirX, dirY) => marginOf(
        bot.x + dirX * T.JUMP_DISTANCE,
        bot.y + dirY * T.JUMP_DISTANCE,
        SIZE
    ) > 0;

    // Добивающий прыжок: закрыть дистанцию, пока соперник у края.
    // Сам по себе прыжок никого не отбрасывает — удар даёт только
    // толчок. Прыжок здесь средство быстро встать в радиус удара и
    // не дать жертве уйти к центру, а заодно гарантированно
    // пережить встречный удар.
    if (bot.cooldowns.jump <= 0 && align >= p.align && !mustBrake
        && gap < p.jumpGap && targetMargin < 90) {
        const kx = target.x - bot.x;
        const ky = target.y - bot.y;
        const kn = Math.hypot(kx, ky) || 1;
        if (canJump(kx / kn, ky / kn)) {
            return decide(kx / kn, ky / kn, true, wantStone);
        }
    }

    // Паника: прыжок тратится на спасение, а не на атаку. Без этого
    // бот выглядел бы глупо — стоял бы с пустым откатом у самого
    // края. Прыжок к центру безопасен в любом состоянии: за край
    // не выносит и неуязвим.
    if (myMargin < p.danger * 0.55 && bot.cooldowns.jump <= 0
        && myD > 1e-6 && !winning) {
        return decide(centerDirX, centerDirY, true, false);
    }

    if (mustBrake) {
        return decide(centerDirX, centerDirY, false, wantStone);
    }

    // Выживание важнее атаки — но не тогда, когда я уже давлю и
    // жертва прижата не сильнее меня. В этот момент отступление стоит
    // партии: жертва уезжает к центру, и если так поступят оба, партия
    // не кончится никогда — именно это и происходило на 6000 тиков.
    //
    // Порог отступа выше порога атаки намеренно: у края можно ещё
    // постоять и ударить, а вот отступить — значит отдать позицию.
    if (myMargin < p.danger && !winning) {
        return decide(centerDirX, centerDirY, false, wantStone);
    }

    // Перерыв между волнами. Бот не атакует и — что важно — не отвечает
    // на атаку: едет по касательной, держа свой радиус. Стоять на месте
    // нельзя, получился бы неподвижный мешок, который снесут с первого
    // раза. Касательное движение держит его живым и делает трудной
    // мишенью: у косого соперника нет лобового, а значит нет и цикла.
    if (!inWave && !winning && myD > 1e-6) {
        const tangentX = -bot.y / myD * p.circle;
        const tangentY = bot.x / myD * p.circle;
        return decide(tangentX, tangentY, false, false);
    }

    

    // Стою между центром и соперником — оттуда удар уходит наружу.
    // Если я снаружи жертвы, сначала обхожу её с внутренней стороны:
    // удар с внешней стороны только помогает врагу уйти в центр.
    const sign = align > 0 ? -1 : 1;
    let aimX = target.x + outX * contact * sign;
    let aimY = target.y + outY * contact * sign;

    // Цель атаки не должна сама лежать за границей: иначе бот идёт
    // прямо на вылет, пока толкает. На квадрате «внутри» — это не
    // круг, а свой квадрат, меньший на радиус игрока.
    const innerLimit = SIZE / 2 - T.PLAYER_RADIUS;
    aimX = clamp(aimX, -innerLimit, innerLimit);
    aimY = clamp(aimY, -innerLimit, innerLimit);

    let dirX = aimX - bot.x;
    let dirY = aimY - bot.y;
    const n = Math.hypot(dirX, dirY);
    if (n > 1e-4) {
        dirX /= n;
        dirY /= n;
    } else {
        dirX = 0;
        dirY = 0;
    }

    // Обычный прыжок на сближение. Наружу прыгаем только если там есть
    // место: прыжок на 300 единиц через поле — это полёт в стену.
    const jump = bot.cooldowns.jump <= 0
        && align >= p.align
        && gap < p.jumpGap
        && canJump(dirX, dirY);

    return decide(dirX, dirY, jump, wantStone);
}

