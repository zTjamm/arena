/**
 * Проверка механики: выталкивается ли соперник на самом деле.
 *
 * Запуск: node test-play.js
 *
 * test-arena.js доказывает, что правила выполняются. Он не доказывает,
 * что игра существует. Если отлёт недостаточен, соперник будет
 * отъезжать на пару пикселей, возвращаться и партия никогда не
 * кончится — а все проверки правил при этом останутся зелёными,
 * потому что правило «выбывает тот, кого вытолкнули за границу»
 * формально выполняется просто никогда.
 *
 * Здесь проверяется сам факт: догнать соперника, зарядить толчок,
 * отпустить кнопку и увидеть, что он вылетел, партия кончилась, а
 * толкающий жив.
 *
 * Сценарий написан как ход человека: идти вперёд, прыжком закрывать
 * дистанцию, **держать толчок**, пока жертва в радиусе, и отпустить
 * кнопку, когда заряд добран. Раньше толчок срабатывал по нажатию,
 * и держать его было можно — теперь он стреляет на отпускании, и
 * весь сценарий перевёрнут: сначала накопление, потом отпускание.
 *
 * Держать кнопку надо **всегда**, пока бой не кончился: отпустить
 * раньше — выстрелить в пустоту и потерять накопленный заряд.
 */

const { T, createArena, addPlayer, step, chargeTier } = require('./game/arena');

let passed = 0;
let failed = 0;
const failures = [];

function check(name, condition, detail) {
    if (condition) {
        passed++;
    } else {
        failed++;
        failures.push(`${name}${detail ? ` — ${detail}` : ''}`);
    }
}

/**
 * A идёт на B с одной стороны, B стоит без движения.
 *
 * Кнопка толчка держится всё время, пока есть с кем бить, и
 * отпускается на один тик — ровно тогда, когда заряд добран и жертва
 * в радиусе. Так и играет человек: копит, потом отпускает.
 *
 * opts.radius — расстояние от центра до стороны, то есть половина
 * квадрата.
 *
 * Возвращает { arena, ticks, maxReach, pushes }.
 */
function chaseDown(opts) {
    const size = opts.radius * 2;
    const arena = createArena({ size });
    addPlayer(arena, 'a', { x: opts.ax, y: 0 });
    addPlayer(arena, 'b', { x: opts.bx, y: 0 });

    let jumpUsed = false;
    let maxReach = Math.abs(opts.bx);
    let pushes = 0;

    for (let i = 0; i < 900 && !arena.finished; i++) {
        const a = arena.players[0];
        const b = arena.players[1];
        const flying = b.fly > 0;
        const gap = Math.abs(b.x - a.x);

        // Прыжок один раз и только по сопернику.
        const wantsJump = !flying && !jumpUsed && gap < 40;
        if (wantsJump) jumpUsed = true;

        // Копить заряд можно, **глядя на жертву**. Направление взгляда
        // следует за ходом, поэтому отступив назад, надо повернуться и
        // дойти снова: кнопку держать, глядя в другую сторону, бессмысленно —
        // удар по конусу в спину не попадёт.
        const facing = a.dirx > 0;

        // Толчок: кнопку держим **всегда, пока скилл готов**. Держать
        // надо и тогда, когда жертва на секунду отошла: отпустил —
        // выстрелил в пустоту и потерял накопленное, а заряд копится
        // на ходу и к моменту встречи уже полный.
        //
        // Отпускаем ровно на один тик, когда заряд добран и жертва в
        // радиусе удара: этот тик и есть удар.
        const ready = a.cooldowns.push <= 0;
        const charged = chargeTier(a.charge) >= 1;
        const inRange = gap <= T.PUSH_RANGE;
        // Целиться можно и не вплотную: удар достаёт на радиус, а веер
        // широкий. Но упираться в жертву нельзя — там толчок не
        // отличить от столкновения.
        const aimed = facing && gap <= T.PUSH_RANGE && !flying;

        // Копить заряд, **не глядя на жертву**, бессмысленно: удар
        // идёт по конусу, и отпустить кнопку в другую сторону — значит
        // выстрелить в поле. Накопленное при этом не сгорает, поэтому
        // отход и разворот ничего не стоят.
        const holding = ready && aimed;

        // Огонь — только когда кнопку действительно пора отпустить.
        const fire = holding && charged;
        if (fire) pushes++;

        // Ход. Правило простое: **копим — стоим**. Взгляд при
        // нулевом вводе сохраняется, поэтому стоя на месте и глядя на
        // жертву, заряд копится, а рука свободна под кнопку.
        //
        // Метаться нельзя, и это самая дорогая ошибка сценария:
        // отступил — жертва оказалась впереди, пошёл вперёд — снова
        // упёрся, и за 900 тиков заряд не набрался ни разу. Разворот
        // поэтому делается в два захода: отход на дистанцию, потом
        // подход, и уже на подходе взгляд направлен на жертву.
        //
        // Пока жертва летит — обязательно отходим. Иначе занимаем
        // ровно то место, откуда её вытолкнули, и она упирается в нас
        // вместо границы: с новым правилом границы это вечный тупик.
        let walk = 0;
        if (flying) walk = -1;
        else if (!inRange) walk = 1;
        else if (!aimed) walk = -1;

        step(arena, {
            a: {
                x: walk,
                jump: wantsJump,
                push: holding && !fire,
            },
            b: {},
        });
        maxReach = Math.max(maxReach, Math.abs(b.x));
    }

    return { arena, ticks: arena.tick, maxReach, pushes };
}

const CASES = [
    ['близко у края',     { radius: 200, ax: -50,  bx: 150 }],
    ['средняя дистанция', { radius: 400, ax: -100, bx: 300 }],
    ['далеко от края',    { radius: 400, ax: -200, bx: 100 }],
    ['почти на краю',     { radius: 400, ax: 0,    bx: 380 }],
    ['тесное поле',       { radius: 120, ax: -60,  bx: 80  }],
];

for (const [label, opts] of CASES) {
    const { arena, ticks, maxReach, pushes } = chaseDown(opts);
    const a = arena.players[0];
    const b = arena.players[1];

    check(`${label}: соперник вылетает`, b.alive === false,
        `остался с запасом ${(opts.radius - Math.abs(b.x)).toFixed(0)}`);
    check(`${label}: партия доиграна`, arena.finished === true,
        `тиков ${ticks}`);
    check(`${label}: победил тот, кто толкал`, arena.winner === 'a',
        `победил ${arena.winner}`);
    check(`${label}: толкающий остался жив`, a.alive === true,
        `вылетел сам, на ${Math.abs(a.x).toFixed(0)}`);

    // Успех именно в том, что соперника отогнали за линию, а не
    // просто тронули: проверяется пройденное расстояние.
    check(`${label}: соперника отогнали за линию`, maxReach > opts.radius,
        `достиг ${maxReach.toFixed(0)}, надо больше ${opts.radius}`);

    check(`${label}: толчок вообще выстреливал`, pushes > 0,
        `выстрелов ${pushes}`);

    // Партия обязана кончиться быстро. Если на это нужны минуты —
// игроки разойдутся раньше, чем кто-то выиграет. Порог в 500 тиков
    // (16 с) — это три удара по полному заряду плюс развороты: ровно
    // столько занимает выталкивание человека с самого края поля.
    check(`${label}: быстро`, ticks <= 500, `${ticks} тиков`);
}


// --- Толчок обязан быть сильнее ходьбы --------------------------------------

{
    // Толчок против ходьбы — на **живом** сопернике, который уходит к
    // центру, и на **полном** заряде.
    //
    // Соперник, который стоит столбом, сравнивать бессмысленно: его
    // расталкивает сама ходьба. Но стоящий соперник — не соперник, а
    // мешок. Живой уходит от давления, и тогда сравнение честное.
    //
    // Считается полный заряд (300 единиц), а не первая ступень: за
    // секунду живой отходит на 190, то есть слабый удар его не вывозит
    // и набивать полный заряд как раз для того, чтобы догонять. В этом
    // и смысл заряда.
    const size = 800;
    const TICKS = 90;

    // Соперник убегает **вправо**: он стоит справа от толкающего, и
    // «наружу» от толкающего — тоже вправо. Если гнать его влево, он
    // сам подойдёт вплотную и проверка превратится в толкок мешка.
    const away = { x: 1, y: 0 };

    const walk = createArena({ size });
    addPlayer(walk, 'a', { x: -20, y: 0 });
    addPlayer(walk, 'b', { x: 10, y: 0 });
    pastGrace(walk);
    for (let i = 0; i < TICKS; i++) step(walk, { a: { x: 1 }, b: away });

    // **Полный** заряд: три секунды держать, чтобы отбросить на 300.
    // Слабая ступень (100) живого соперника не вывозит — за секунду он
    // отходит на 190, и набивать полный заряд как раз для того, чтобы
    // догонять. Смысл заряда ровно в этом, и сравнивать надо сильную
    // ступень за те же три секунды, что и ходьбу.
    // A копит заряд **и догоняет**: стоять на месте, пока жертва
    // убегает, — не игра, а фарс. Убегающий за три секунды отходит на
    // 570 единиц, радиус удара — 54, и удар в пустоту не достаёт.
    const pushed = createArena({ size });
    addPlayer(pushed, 'a', { x: -20, y: 0 });
    addPlayer(pushed, 'b', { x: 10, y: 0 });
    pastGrace(pushed);
    for (let i = 0; i < TICKS; i++) {
        const A = pushed.players[0];
        const B = pushed.players[1];
        const gap = B.x - A.x;
        const charged = chargeTier(A.charge) >= 3;
        const fire = charged && gap <= T.PUSH_RANGE && B.fly === 0;
        step(pushed, {
            a: { x: gap > T.PUSH_RANGE - 6 ? 1 : 0, push: !fire },
            b: away,
        });
    }
    for (let i = 0; i < 40; i++) step(pushed, { b: away });

    // Оба сценария упирают соперника в границу и там его держат, поэтому
    // сравнивать пройденное расстояние бессмысленно — упереться можно
    // и ходьбой. Сравнивается то, ради чего всё и затевалось: **кого
    // вообще можно выбить с поля**.
    //
    // Ходьба прижимает к границе и держит. Выбивает только удар: у
    // летящего граница не держит, и он уходит за неё.
    check('ходьба соперника не выбивает с поля',
        walk.players[1].alive === true,
        `выбит ходьбой, запас ${(400 - Math.abs(walk.players[1].x)).toFixed(0)}`);
    check('толчок выбивает соперника с поля',
        pushed.players[1].alive === false,
        `жив, запас ${(400 - Math.abs(pushed.players[1].x)).toFixed(0)}`);

    // Слабый удар рядом с краем выбивает не хуже сильного: важна не
    // ступень сама по себе, а сколько осталось до границы. Поэтому
    // проверяется обратное: у края хватает и слабой ступени.
    const weak = createArena({ size: 200 });
    addPlayer(weak, 'a', { x: 0, y: 0 });
    addPlayer(weak, 'b', { x: 70, y: 0 });
    pastGrace(weak);
    step(weak, { a: { x: 1, push: true } });
    for (let i = 0; i < 14; i++) step(weak, { a: { push: true } });
    step(weak, { a: { push: false } });
    for (let i = 0; i < 20; i++) step(weak, {});

    check('слабого заряда у самого края хватает',
        weak.players[1].alive === false,
        `жив с запасом ${(100 - Math.abs(weak.players[1].x)).toFixed(0)}`);
}


/**
 * Прожить первые секунды партии, когда бить ещё нельзя.
 *
 * Первые SPAWN_GRACE секунд удара нет, и любой сценарий, который
 * бьёт сразу после расстановки, просто не выстрелит. Проверять
 * отсчёт — дело другого теста, здесь он просто пропускается.
 */
function pastGrace(arena) {
    const ticks = Math.ceil(T.SPAWN_GRACE / T.TICK);
    for (let i = 0; i < ticks; i++) step(arena, {});
}


// --- Прыжок спасает от вылета -----------------------------------------------

{
    // Прыжок неуязвим и не выносит за край, но приземлиться можно уже
    // на границе. Проверяем именно это: дошёл, а не вылетел.
    const arena = createArena({ size: 200 });
    addPlayer(arena, 'a', { x: 0, y: 0 });
    addPlayer(arena, 'b', { x: 0, y: 0 });

    step(arena, { b: { x: 1, jump: true } });
    for (let i = 0; i < 30 && arena.players[1].jumpLeft > 0; i++) step(arena, {});

    check('прыжок доводит до точки, не выбрасывая',
        arena.players[1].alive === true && arena.players[1].x > 90,
        `x ${arena.players[1].x.toFixed(0)}, жив ${arena.players[1].alive}`);
}


// --- Камень спасает от толчка -----------------------------------------------

{
    // Каменный от удара отскакивает сам, а не улетает. Это и есть
    // весь смысл защиты: без неё толчок против камня — тот же удар,
    // только в другую сторону.
    const size = 800;
    const arena = createArena({ size });
    addPlayer(arena, 'a', { x: 0, y: 0 });
    addPlayer(arena, 'b', { x: 70, y: 0 });
    arena.players[0].dirx = 1;
    pastGrace(arena);

    // Камень включается после отсчёта: он держится две секунды, а
    // отсчёт длится три, и окаменение до него сгорело бы впустую.
    step(arena, { b: { stone: true } });
    for (let i = 0; i < 15; i++) step(arena, { a: { push: true } });
    step(arena, { a: { push: false } });

    const b = arena.players[1];
    check('каменный не улетел', b.fly === 0 && Math.abs(b.x - 70) < 30,
        `x ${b.x.toFixed(0)}`);
    check('бьющий отскочил назад',
        arena.players[0].fly > 0 && arena.players[0].flyx < 0,
        `полёт ${arena.players[0].fly.toFixed(0)} в ${arena.players[0].flyx}`);
}


// --- Итог -----------------------------------------------------------------

console.log(`механика: ${passed} проверок пройдено, ${failed} провалено`);
if (failed > 0) {
    for (const f of failures) console.log(`  ПРОВАЛ: ${f}`);
    process.exit(1);
}